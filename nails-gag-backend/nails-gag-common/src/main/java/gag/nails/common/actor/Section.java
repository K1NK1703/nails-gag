package gag.nails.common.actor;

/** Разделы админки. На каждый у пользователя свой {@link AccessLevel}. */
public enum Section {
    /** Записи, отметки визита, предоплата, предложение приехать раньше. */
    BOOKINGS,
    /** Слоты, шаблоны, ротация. */
    SCHEDULE,
    /** Карточки клиентов, заметки, признак предоплаты, объединение, блокировка. */
    CLIENTS,
    /** Услуги и цены. */
    CATALOG,
    /** Правила записи и их журнал. */
    BOOKING_SETTINGS,
    /** Доходы и расходы. */
    FINANCE,
    /** Фотографии работ. */
    PORTFOLIO,
    /** Редакции политики и оферты. */
    DOCUMENTS,
    /** Роли, права пользователей, журналы прав и входов. */
    ACCESS
}
