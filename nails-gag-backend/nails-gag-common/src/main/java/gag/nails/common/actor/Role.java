package gag.nails.common.actor;

/** Роли аккаунта. У одного аккаунта может быть несколько. */
public enum Role {
    /** Клиент с аккаунтом: свои записи и данные. */
    CLIENT,
    /** Мастер: расписание, записи, клиенты, каталог, настройки правил. */
    MASTER,
    /** Разработчик: всё, что мастер, плюс техническое. */
    DEVELOPER
}
