package gag.nails.files;

/**
 * Уборка хранилища: ночная задача модуля ({@code nails-gag.files.jobs}), в тестах — вызов напрямую. Повторный вызов
 * безопасен.
 */
public interface FileMaintenance {

    /**
     * Удаляет «сирот» — файлы, которые владелец не привязал за сутки после загрузки: строки сразу, файлы на диске после
     * фиксации.
     *
     * @return сколько файлов удалено
     */
    int removeOrphans();

    /**
     * Сверяет диск с базой: удаляет каталоги файлов без строки в базе и остатки незавершённых загрузок старше суток.
     * Добивает файлы, которые не удалось стереть после фиксации удаления или отката загрузки.
     *
     * @return сколько каталогов и временных файлов удалено
     */
    int removeStrayDirectories();
}
