package gag.nails.identity;

/** Обслуживание: вызывается фоновой задачей раз в сутки, в тестах — напрямую. */
public interface IdentityMaintenance {

    /**
     * Удаляет просроченные сессии (90 дней от входа или 30 без активности), незавершённые регистрации
     * старше 30 минут и события входа старше 90 дней. Каждый шаг — своя транзакция: сбой одного
     * логируется и не мешает другим. Возвращает число удалённых сессий.
     */
    int cleanUp();
}
