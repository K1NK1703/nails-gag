package gag.nails.booking.model;

/**
 * Чем обернулась полученная предоплата. Вычисляется по тому, чем закончилась запись; у отменённой записи и неявки
 * мастер может переопределить исход «удержана ↔ возвращена».
 */
public enum PrepaymentOutcome {
    /** В счёт визита: запись активна или выполнена; отдельным доходом не считается. */
    APPLIED,
    /** Удержана: неявка, поздняя отмена клиентом, отказ из-за опоздания или отмена записи удалившего аккаунт. */
    KEPT,
    /** Возвращена клиенту: отмена в окне или мастером. */
    RETURNED
}
