package gag.nails.booking.model;

/** Почему запись отменена. */
public enum CancelReason {
    /** Клиентом в окне бесплатной отмены. */
    CLIENT,
    /** Клиентом позже окна бесплатной отмены: следующая запись — по предоплате. */
    CLIENT_LATE,
    /** Мастером; без последствий для клиента. */
    MASTER,
    /** Мастер отказал из-за опоздания; приравнивается к поздней отмене. */
    LATE_ARRIVAL,
    /** Предоплата не получена к сроку. */
    PREPAYMENT_TIMEOUT,
    /**
     * Мастер отменил запись клиента, удалившего аккаунт: признак предоплаты не ставится, полученная предоплата
     * удерживается. До 2026-10-31 так отменялись будущие записи при самом удалении аккаунта.
     */
    ACCOUNT_DELETED
}
