package gag.nails.booking;

import gag.nails.common.error.InternalException;

/**
 * Фоновые задачи записей. Планировщик вызывает их раз в минуту, а удаление референсов — раз в сутки; вызвать можно и
 * вручную. Повторный вызов безопасен: уже обработанные записи не затрагиваются. Отмена и истечение обрабатывают
 * каждую запись в своей транзакции, сбой на одной не останавливает остальные.
 */
public interface BookingMaintenance {

    /**
     * Отменяет записи, не дождавшиеся предоплаты к сроку: слот освобождается, признак обязательной
     * предоплаты у клиента остаётся.
     *
     * @return сколько записей отменено
     */
    int cancelOverduePrepayments();

    /**
     * Предложения приехать раньше, оставшиеся без ответа к началу слота, истекают.
     *
     * @return сколько предложений истекло
     */
    int expireEarlierTimeOffers();

    /**
     * Удаляет вместе с файлами референсы записей, срок хранения которых истёк
     * ({@code nails-gag.booking.reference-retention-days}, по умолчанию 30 дней): у отменённой записи он считается от
     * отмены, у любой другой, в том числе не отмеченной мастером, — от начала визита (согласованного более раннего
     * времени или начала слота). Записи обрабатываются пачками, каждая пачка — в своей транзакции; файлы на диске
     * стираются после её фиксации. Сбой одной записи не мешает остальным: он пишется в лог, а запись ждёт следующего
     * запуска. Вызывать вне транзакции.
     *
     * @return сколько референсов удалено
     * @throws InternalException если вызван внутри транзакции
     */
    int removeExpiredReferences();
}
