package gag.nails.notifications.internal.dispatch;

import gag.nails.notifications.model.Channel;

/**
 * Канал доставки (спека §3.2, §3.5): почта, Telegram; новый канал (SMS) — ещё одна реализация этого интерфейса и
 * значение {@link Channel}. Реализации — бины модуля; канала без бина на сервере нет, как и канала, который сообщает
 * {@link #configured()} {@code false}: такому каналу доставки не создаются. Реализаций одного канала может быть
 * несколько (подменная рядом с ненастроенной настоящей), но настроенной — не больше одной.
 *
 * <p>{@link #send} вызывается вне транзакции, по одной доставке за раз, и может ходить наружу сколько угодно долго в
 * пределах аренды доставки (5 минут). Исход сообщается результатом, а не исключением: исключение отправка считает
 * временным сбоем ({@link SendResult.Retry}). Адреса, тексты и токены в логи и исключения не попадают (спека §6).
 */
public interface NotificationChannel {

    /** Какой это канал; у каждого канала — не больше одной настроенной реализации. */
    Channel channel();

    /** Канал настроен на сервере (почтовый сервер и отправитель, токен бота); не настроен — недоступен всем. */
    boolean configured();

    /**
     * Отправляет текст получателю. Адрес — поле получателя своего канала: отправка зовёт канал, только если оно задано.
     *
     * @return {@link SendResult.Sent} — доставлено; {@link SendResult.Retry} — временный сбой, повторить позже;
     *     {@link SendResult.Fail} — постоянный отказ, повторять бессмысленно
     */
    SendResult send(ResolvedRecipient recipient, RenderedText text);
}
