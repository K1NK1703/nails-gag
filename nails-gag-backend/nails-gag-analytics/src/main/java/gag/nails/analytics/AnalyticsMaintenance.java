package gag.nails.analytics;

import gag.nails.common.error.InternalException;

/**
 * Уборка счётчика посещений. Планировщик вызывает её раз в сутки ({@code nails-gag.analytics.jobs.purge-cron}, по
 * умолчанию в 00:30 по времени салона) и один раз после старта приложения — убрать дни, пока оно не работало; вызвать
 * можно и вручную. Повторный вызов безопасен: убирать уже нечего.
 */
public interface AnalyticsMaintenance {

    /**
     * Удаляет соли и отпечатки посетителей за дни раньше сегодняшнего (день — в поясе салона по часам приложения),
     * одной транзакцией. После этого восстановить, кто был в прошедший день, нельзя: без соли дня отпечаток не
     * сопоставить ни с адресом, ни с браузером. Дневные счётчики, в том числе число посетителей, остаются; соль и
     * отпечатки сегодняшнего дня не трогаются — приём продолжает узнавать посетителей дня. Вызывать вне транзакции.
     *
     * @return сколько отпечатков удалено
     * @throws InternalException если вызван внутри транзакции
     */
    int purgeExpired();
}
