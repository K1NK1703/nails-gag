package gag.nails.analytics;

import gag.nails.analytics.command.RecordEvent;
import org.jspecify.annotations.Nullable;

/**
 * Приём событий сайта — системная операция без {@code Actor}: события шлют анонимные посетители. Событие сразу
 * прибавляется к счётчикам дня (день — в поясе салона по часам приложения, присланное время не используется); сырые
 * события, IP и {@code User-Agent} не хранятся и не пишутся в лог.
 */
public interface AnalyticsIngest {

    /**
     * Прибавляет событие к счётчикам дня; неверное событие, робот и не IP-литерал молча игнорируются. Не бросает
     * {@code RuntimeException}: сбой записи пишется в лог (с ограничением частоты), частично записанных счётчиков не
     * остаётся. Когда одновременных записей слишком много, событие отбрасывается без ожидания.
     *
     * <p>Пишет в своей транзакции ({@code REQUIRES_NEW}): вызов изнутри чужой транзакции её не затрагивает — ни сбой
     * записи не прерывает её, ни её откат не отменяет посчитанного.
     *
     * <p>Каждый {@code page_view} считает и уникального посетителя дня по отпечатку {@code SHA-256(соль дня ‖ байты
     * адреса ‖ 0x00 ‖ userAgent)}; {@code page_view} с {@code entry = true} считает ещё источник и устройство. Сверх
     * предела посетителей за день ({@code nails-gag.analytics.max-visitors-per-day}) новые посетители не отмечаются,
     * просмотры считаются.
     *
     * @param event событие как оно пришло
     * @param ip IP-литерал посетителя (IPv4 или IPv6, DNS не используется) — только для суточного отпечатка
     * @param userAgent заголовок {@code User-Agent}; пустой или похожий на робота — событие игнорируется
     */
    void record(RecordEvent event, String ip, @Nullable String userAgent);
}
