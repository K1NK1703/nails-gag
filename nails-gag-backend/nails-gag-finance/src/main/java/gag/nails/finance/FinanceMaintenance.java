package gag.nails.finance;

import gag.nails.common.error.InternalException;

/**
 * Фоновая задача финансов. Планировщик вызывает её раз в сутки ({@code nails-gag.finance.jobs.recurring-cron}, по
 * умолчанию в 00:15 по времени салона) и один раз после старта приложения — догнать дни, пока оно не работало;
 * вызвать можно и вручную. Повторный вызов безопасен: ничего не дублирует.
 */
public interface FinanceMaintenance {

    /**
     * Создаёт записи повторяющихся шаблонов за наступившие дни, по сегодняшний включительно, догоняя пропущенные
     * запуски (правила — {@link FinanceRecurring}). Каждый шаблон — в своей транзакции: его записи, их журнал (от
     * имени системы) и сдвиг отметки прогресса фиксируются вместе. Сбой одного шаблона не мешает остальным: он
     * пишется в лог по идентификатору шаблона, а шаблон ждёт следующего запуска. Шаблон, который в это время меняют
     * (его строка под блокировкой), в этом запуске пропускается: правка сама создаёт его записи за наступившие дни,
     * а если она откатится — их создаст следующий запуск (прогресс шаблона не сдвинут). Вызывать вне транзакции.
     *
     * @return сколько записей создано
     * @throws InternalException если вызван внутри транзакции
     */
    int createDueRecurringEntries();
}
