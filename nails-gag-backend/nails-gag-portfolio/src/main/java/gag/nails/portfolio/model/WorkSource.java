package gag.nails.portfolio.model;

/** Откуда работа и нужно ли для её публикации согласие клиента. */
public enum WorkSource {

    /**
     * Работа клиента из его записи на сайте: опубликована, только пока у клиента есть согласие на публикацию фото;
     * отзыв согласия сразу снимает все его работы.
     */
    CLIENT,

    /** Работа реального клиента, согласие на публикацию получено вне сайта (отметка мастера). */
    CLIENT_OUTSIDE_SITE,

    /** Ничья работа: сгенерированная картинка, эскиз, руки мастера. Согласие не нужно. */
    EXAMPLE
}
