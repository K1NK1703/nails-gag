package gag.nails.clients.internal.client;

import java.util.Optional;
import java.util.UUID;

/** Фрагмент {@link ClientRepository}: карточка под блокировкой строки. */
interface ClientLocking {

    /**
     * Карточка под блокировкой строки на запись до конца транзакции, перечитанная из базы уже под блокировкой: если
     * карточка была загружена в этой транзакции раньше, её прежнее состояние заменяется зафиксированным. Пусто —
     * карточки нет, в том числе удалённой объединением, которого пришлось ждать.
     *
     * <p>Правило модуля: любой путь, меняющий карточку, и особенно вставляющий строки со ссылкой на неё (согласия,
     * отзывы, журнал признака предоплаты), сначала берёт её блокировку этим методом. Тогда кто пришёл вторым, увидит
     * результат первого и не затрёт его старым состоянием, а вставка строки журнала не встанет поперёк удаления
     * карточки объединением (взаимная блокировка через внешний ключ).
     *
     * <p>Порядок блокировок: карточка, затем строки согласий и то, что берут синхронные подписчики событий (аккаунт,
     * записи); две карточки — в порядке id. Известный встречный порядок — поздняя отмена записи (запись → клиент),
     * он описан у подписчика {@code ClientErased} в модуле записей.
     *
     * <p>Несохранённые изменения карточки, сделанные вызывающим до вызова, сначала сбрасываются в базу (иначе
     * перечитывание их потеряло бы); сделанные по старому состоянию, они могут перезаписать результат того, кого
     * пришлось ждать. Поэтому карточку меняют только после этого вызова.
     */
    Optional<ClientEntity> findLockedById(UUID id);
}
