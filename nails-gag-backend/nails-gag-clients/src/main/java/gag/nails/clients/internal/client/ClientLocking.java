package gag.nails.clients.internal.client;

import java.util.Optional;
import java.util.UUID;

/** Фрагмент {@link ClientRepository}: карточка под блокировкой строки. */
interface ClientLocking {

    /**
     * Карточка под блокировкой строки на запись до конца транзакции, перечитанная из базы уже под блокировкой: если
     * карточка была загружена в этой транзакции раньше, её прежнее состояние заменяется зафиксированным (несохранённые
     * изменения сначала сбрасываются в базу). Пусто — карточки нет, в том числе удалённой объединением, которого
     * пришлось ждать.
     *
     * <p>Ею сериализуются запись и отзыв согласия, объединение, обезличивание, блокировка и её снятие: кто пришёл
     * вторым, увидит результат первого. Порядок блокировок: карточка, затем строки согласий и то, что берут
     * синхронные подписчики событий (аккаунт, записи); две карточки — в порядке id. Известные встречные порядки
     * (поздняя отмена записи, вход) описаны у подписчиков {@code ClientErased} и {@code ClientBlocked}.
     */
    Optional<ClientEntity> findLockedById(UUID id);
}
